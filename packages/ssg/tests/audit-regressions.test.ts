test("image names for memes and success illustrations survive the URL round trip", () =>
  fixture(async (root) => {
    await writeFile(path.join(root, "master.bin"), "master");
    await writeFile(path.join(root, "src/index.ts"), 'export default "home"');
    const descriptors = [
      {
        id: "meme",
        source: "master.bin",
        directory: "images",
        name: "#lesgens",
        widths: [256],
        formats: ["jpg"],
      },
      {
        id: "success",
        source: "master.bin",
        directory: "images",
        name: "100%completed",
        widths: [256],
        formats: ["png"],
      },
    ];
    await build({
      root,
      assets: images({
        descriptors,
        converter: {
          formats: ["jpg", "png"],
          async decode() {
            return { width: 512, height: 512 };
          },
          async encode(_image, variant) {
            return new TextEncoder().encode(variant.format);
          },
        },
      }),
    });
    const server = Bun.serve({
      hostname: "127.0.0.1",
      port: 0,
      fetch(request) {
        return new Response(
          Bun.file(path.join(root, "dist", decodeURIComponent(new URL(request.url).pathname))),
        );
      },
    });
    try {
      for (const descriptor of descriptors) {
        const format = descriptor.formats[0]!;
        const response = await fetch(new URL(imageUrl(descriptor, 256, format), server.url));
        expect(response.status).toBe(200);
        expect(await response.text()).toBe(format);
      }
    } finally {
      await server.stop(true);
    }
  }));
