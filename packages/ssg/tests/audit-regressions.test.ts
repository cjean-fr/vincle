import { expect, test } from "bun:test";
import { mkdir, mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises";
import path from "node:path";

import { dev } from "../src/dev.js";
import { imageUrl, images } from "../src/image.js";
import { build, discoverPages } from "../src/index.js";

async function fixture(run: (root: string) => Promise<void>) {
  const root = await mkdtemp(path.join(import.meta.dirname, "../.audit-"));
  try {
    await mkdir(path.join(root, "src"));
    await mkdir(path.join(root, "external"));
    await run(root);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

test("discovery follows file and directory links, with target-relative module imports", () =>
  fixture(async (root) => {
    await writeFile(
      path.join(root, "external/page.tsx"),
      'import {label} from "./_label"; export default () => <p>{label}</p>',
    );
    await writeFile(path.join(root, "external/_label.ts"), 'export const label = "target";');
    await writeFile(path.join(root, "src/_label.ts"), 'export const label = "link";');
    await symlink("../external/page.tsx", path.join(root, "src/linked.tsx"));
    await symlink("../external", path.join(root, "src/directory"));
    const pages = await discoverPages({ src: path.join(root, "src") });
    expect(pages.map((page) => page.source.route)).toEqual(["/directory/page", "/linked"]);
    await build({ root, assets: false });
    expect(await readFile(path.join(root, "dist/linked/index.html"), "utf8")).toBe("<p>target</p>");
    expect(await readFile(path.join(root, "dist/directory/page/index.html"), "utf8")).toBe(
      "<p>target</p>",
    );
  }));

test("directory cycles and broken links fail discovery instead of being silently omitted", () =>
  fixture(async (root) => {
    await symlink(".", path.join(root, "src/loop"));
    await expect(discoverPages({ src: path.join(root, "src") })).rejects.toThrow(
      "Symbolic link cycle",
    );
    await rm(path.join(root, "src/loop"));
    await symlink("missing.tsx", path.join(root, "src/broken.tsx"));
    await expect(discoverPages({ src: path.join(root, "src") })).rejects.toThrow(
      "Could not read source directory",
    );
  }));

test("a page discovered outside src stops layout lookup at the filesystem root", () =>
  fixture(async (root) => {
    await writeFile(path.join(root, "external/page.tsx"), "export default () => <p>outside</p>");
    await build({
      root,
      assets: false,
      discover: () =>
        discoverPages({ src: path.join(root, "external") }).then((pages) =>
          pages.map((page) => ({
            ...page,
            source: { ...page.source, src: path.join(root, "src") },
          })),
        ),
    });
    expect(await readFile(path.join(root, "dist/page/index.html"), "utf8")).toBe("<p>outside</p>");
  }));

test(
  "dev follows a linked page and refreshes target-side relative imports",
  () =>
    fixture(async (root) => {
      await writeFile(
        path.join(root, "external/page.tsx"),
        'import {label} from "./_label"; export default () => <p>{label}</p>',
      );
      const dependency = path.join(root, "external/_label.ts");
      await writeFile(dependency, 'export const label = "first-target";');
      await symlink("../external/page.tsx", path.join(root, "src/linked.tsx"));
      const server = await dev({
        root,
        assets: false,
        vite: {
          configFile: false,
          logLevel: "silent",
          server: { host: "127.0.0.1", port: 0, watch: { usePolling: true, interval: 50 } },
        },
      });
      try {
        const address = server.vite.httpServer!.address();
        if (!address || typeof address === "string") throw new Error("Expected listening server");
        const url = `http://127.0.0.1:${address.port}/linked/`;
        expect(await (await fetch(url)).text()).toContain("first-target");
        await writeFile(dependency, 'export const label = "second-target";');
        let html = "";
        for (let attempt = 0; attempt < 100; attempt++) {
          html = await (await fetch(url)).text();
          if (html.includes("second-target")) break;
          await new Promise((resolve) => setTimeout(resolve, 50));
        }
        expect(html).toContain("second-target");
      } finally {
        await server.close();
      }
    }),
  20_000,
);

test("encoded image URLs retrieve the generated bytes in dev and published output", () =>
  fixture(async (root) => {
    await writeFile(path.join(root, "master.bin"), "master");
    await writeFile(path.join(root, "src/index.ts"), 'export default "home"');
    const descriptor = {
      id: "photo",
      source: "master.bin",
      directory: "images été/#?%",
      name: "photo #1?% café",
      widths: [256],
      formats: ["avif"],
    };
    const assets = images({
      descriptors: [descriptor],
      converter: {
        formats: ["avif"],
        async decode() {
          return { width: 512, height: 512 };
        },
        async encode() {
          return new TextEncoder().encode("image-bytes");
        },
      },
    });
    const url = imageUrl(descriptor, 256, "avif");
    expect(url).toBe("/images%20%C3%A9t%C3%A9/%23%3F%25/photo%20%231%3F%25%20caf%C3%A9-256.avif");
    await build({ root, assets });
    const filename = path.join(root, "dist", descriptor.directory, descriptor.name + "-256.avif");
    expect(await readFile(filename, "utf8")).toBe("image-bytes");
    const published = Bun.serve({
      hostname: "127.0.0.1",
      port: 0,
      fetch(request) {
        return new Response(
          Bun.file(path.join(root, "dist", decodeURIComponent(new URL(request.url).pathname))),
        );
      },
    });
    try {
      expect(await (await fetch(new URL(url, published.url))).text()).toBe("image-bytes");
    } finally {
      await published.stop(true);
    }
    const server = await dev({
      root,
      assets,
      vite: { configFile: false, logLevel: "silent", server: { host: "127.0.0.1", port: 0 } },
    });
    try {
      const address = server.vite.httpServer!.address();
      if (!address || typeof address === "string") throw new Error("Expected listening server");
      const response = await fetch(`http://127.0.0.1:${address.port}${url}`);
      expect(response.status).toBe(200);
      expect(await response.text()).toBe("image-bytes");
    } finally {
      await server.close();
    }
  }));

