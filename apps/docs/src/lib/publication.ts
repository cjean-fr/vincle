export function llmsTxt(
  pages: readonly { url: string; title: string }[],
  config: ResolvedDocsConfig,
): string {
  const lines: string[] = [
    `# ${config.title}: ${config.tagline ?? "Documentation"}`,
    "",
    `> ${config.description}`,
    "",
    "Every page is also available as Markdown at its URL plus `.md` (home page: `/index.md`).",
    "",
    "## Pages",
    "",
  ];
  for (const page of pages) lines.push(`- [${page.title}](${fullUrl(page.url, ssg.site)})`);
  lines.push("");
  return lines.join("\n");
}

export async function llmsFullTxt(
  pages:
    | Iterable<{ url: string; title: string; text: string }>
    | AsyncIterable<{ url: string; title: string; text: string }>,
  config: ResolvedDocsConfig,
): Promise<string> {
  let content = [`# ${config.title}: Full documentation`, "", `> ${config.description}`, ""].join(
    "\n",
  );
  for await (const page of pages)
    content += [
      "",
      "---",
      `# ${page.title}`,
      `Source: ${fullUrl(page.url, ssg.site)}`,
      "",
      page.text,
      "",
    ].join("\n");
  return content;
}

const BLOCKS_TO_DROP: RegExp[] = [
  /<script\b[^>]*>[\s\S]*?<\/script>/gi,
  /<style\b[^>]*>[\s\S]*?<\/style>/gi,
  /<nav\b[^>]*>[\s\S]*?<\/nav>/gi,
  /<footer\b[^>]*>[\s\S]*?<\/footer>/gi,
];

const NAMED_ENTITIES: ReadonlyArray<readonly [RegExp, string]> = [
  [/&amp;/g, "&"],
  [/&lt;/g, "<"],
  [/&gt;/g, ">"],
  [/&quot;/g, '"'],
  [/&#39;/g, "'"],
  [/&#x27;/g, "'"],
  [/&#x60;/g, "`"],
  [/&#x2F;/g, "/"],
];

/** The text of the first paragraph in `<main>`: what a page says before its first heading. */
function firstParagraph(html: string): string | undefined {
  const paragraph = mainContent(html)?.match(/<p\b[^>]*>([\s\S]*?)<\/p>/i)?.[1];
  return paragraph === undefined ? undefined : htmlToText(paragraph) || undefined;
}

/** The `<main>` content of a page, or `undefined` when the page has none. */
function mainContent(html: string): string | undefined {
  return html.match(/<main\b[^>]*>([\s\S]*?)<\/main>/i)?.[1];
}

/** The `<h2>`/`<h3>` of `<main>` that carry an id, for search to land on. */
export function headingsOf(html: string): { id: string; text: string }[] {
  const headings: { id: string; text: string }[] = [];
  const heading = /<h([23])\b[^>]*\bid="([^"]+)"[^>]*>([\s\S]*?)<\/h\1>/gi;
  for (const [, , id, inner] of (mainContent(html) ?? "").matchAll(heading)) {
    // The `#` permalink is chrome, not part of the heading.
    const text = htmlToText(inner!.replace(/<a\b[^>]*docs-heading-anchor[\s\S]*?<\/a>/gi, ""));
    if (text) headings.push({ id: id!, text });
  }
  return headings;
}

/**
 * HTML string → readable plain text.
 *
 * Best-effort by design: the pages being scraped are generated by this very
 * project (satteri markdown + Vincle JSX), so the tag shapes are known. It is
 * a fallback for the post-string pipeline (TOC labels, llms.txt, search
 * index), not a substitute for walking the VNode tree.
 */
function htmlToText(html: string, options?: { mainOnly?: boolean }): string {
  let body = options?.mainOnly ? (mainContent(html) ?? html) : html;
  for (const re of BLOCKS_TO_DROP) body = body.replace(re, " ");
  body = body.replace(/<[^>]+>/g, " ");
  for (const [re, value] of NAMED_ENTITIES) body = body.replace(re, value);
  body = body
    .replace(/&#x([0-9a-fA-F]+);/g, (_, h: string) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, c: string) => String.fromCodePoint(Number(c)));
  return body.replace(/\s+/g, " ").trim();
}

/**
 * Social cards are native sharp work, not page rendering: run sequentially they
 * became the build's second bottleneck. A bounded pool lets sharp overlap with
 * itself while keeping peak memory low; beyond a handful, the thread pool is
 * saturated.
 */
const SOCIAL_CARD_CONCURRENCY = 8;

/** Search, LLM and social artifacts consume the same final HTML, read once per page. */
export const documentationArtifacts: SsgPlugin = {
  name: "documentation-artifacts",
  async publish(context) {
    const search: SearchDocument[] = [];
    const pages: { url: string; title: string; text: string }[] = [];
    const cardTasks: (() => Promise<void>)[] = [];
    for (const page of context.outputs) {
      if (page.meta.search === false) continue;
      const html = await page.read();
      const title = page.meta.title ?? page.url;
      const main = htmlToText(html, { mainOnly: true });
      const keywords = (page.meta as { keywords?: string[] }).keywords;
      search.push({
        url: page.url,
        title,
        headings: headingsOf(html),
        text: main,
        ...(keywords === undefined ? {} : { keywords }),
      });
      if (hasSocialCard(page.url)) {
        const description = (page.meta as { description?: string }).description;
        const card = {
          title,
          section: tabFor(docs.tabs, page.url)?.label ?? null,
          summary: description ?? summarize(firstParagraph(html) ?? main, title),
        };
        cardTasks.push(() =>
          context.emit({ path: socialCardPath(page.url), content: () => socialCardPng(card) }),
        );
      }
      pages.push({ url: page.url, title, text: htmlToText(html) });
    }
    // Cards only write distinct files, so their emission order does not matter.
    let nextCard = 0;
    await Promise.all(
      Array.from({ length: Math.min(SOCIAL_CARD_CONCURRENCY, cardTasks.length) }, async () => {
        while (nextCard < cardTasks.length) await cardTasks[nextCard++]!();
      }),
    );
    await context.emit({ path: "search-index.json", content: JSON.stringify(search) });
    await context.emit({ path: "llms.txt", content: llmsTxt(pages, docs) });
    await context.emit({ path: "llms-full.txt", content: () => llmsFullTxt(pages, docs) });
  },
};
