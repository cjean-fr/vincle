import { jsxAttr, jsxEscape } from "@vincle/core/jsx-precompile-runtime";
import precompileTransform from "@vincle/precompile";
/**
 * Generate `realworld/shared.precompiled.mjs` from `realworld/shared.tsx` with
 * the real `@vincle/precompile` transform (vincle-dialect serializers, so the
 * emitted bytes are promised equal to the dynamic render).
 *
 * The transform rewrites text, it does not transpile: the TS annotations of the
 * source survive, and Node's type stripping does not reach `.mjs` — the bench
 * runs under Node too. The emitted file is therefore stripped through
 * `Bun.build` with `modules: "preserve"`: transpile only, imports left alone.
 *
 * Regenerate: `bun run gen:precompile`
 */
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { NAME, generatePurchases } from "./realworld/data.js";
import { render as renderTsx } from "./realworld/shared.tsx";
import { render as renderJs } from "./realworld/vincle.js";

const PURCHASES = generatePurchases(1_000);

const srcUrl = new URL("./realworld/shared.tsx", import.meta.url);
const source = readFileSync(srcUrl, "utf8");
const result = precompileTransform(source, fileURLToPath(srcUrl), undefined, jsxAttr, jsxEscape);
if (!result) throw new Error("precompileTransform returned null — no JSX found?");

const dir = mkdtempSync(join(tmpdir(), "vincle-precompile-"));
// `.tsx`, not `.ts`: a preserved component lands as `${<Comp/>}` inside a
// template hole, which the TS parser reads as a type assertion in a `.ts` file.
const tmpFile = join(dir, "shared.precompiled.tsx");
try {
  writeFileSync(tmpFile, result.code);
  // The transform rewrites what it can inline; preserved component elements come
  // out as JSX still, for the compilation step to finish — in the real pipeline
  // that is the bundler, here it must use the same runtime the transform
  // injected so the leftover `jsx()` calls land where the helpers do.
  const outDir = join(dir, "out");
  const built = await Bun.build({
    entrypoints: [tmpFile],
    modules: "preserve",
    format: "esm",
    jsx: { importSource: "@vincle/core" },
    // The temp file lives outside the workspace, so nothing resolves; the
    // imports are the bench's own dependencies, kept for the runtime to find.
    external: ["@vincle/core", "@vincle/core/*"],
    outdir: outDir,
  });
  if (!built.success) throw new Error("Bun.build failed: " + JSON.stringify(built.logs));
  const emitted = readdirSync(outDir).find((f) => f.startsWith("shared.precompiled"));
  if (!emitted) throw new Error("Bun.build emitted nothing: " + JSON.stringify(built.logs));
  const js = readFileSync(join(outDir, emitted), "utf8")
    // The bundler's sourceURL marker names the temp file; the emitted module is
    // the source of truth, the marker is noise.
    .split("\n")
    .filter((line) => !line.includes("vincle-precompile-"))
    .join("\n");
  const outUrl = new URL("./realworld/shared.precompiled.mjs", import.meta.url);
  const banner = "// Generated by gen-precompile.mjs from shared.tsx — regenerate, don't edit.\n";
  writeFileSync(outUrl, banner + js);
  console.log(`wrote ${js.length} bytes of transformed code`);

  // Three spellings of one document must emit identical bytes: the `jsx()` port,
  // the JSX source rendered through the dynamic path, and the transformed code.
  // Held here rather than in the bench: the JSX source needs a runtime that
  // reads `.tsx`, and Node's type stripping stops at the extension.
  const { render: renderPrecompiled } = await import(outUrl.href);
  const [jsPort, tsxPort, precompiled] = await Promise.all([
    renderJs(NAME, PURCHASES),
    renderTsx(NAME, PURCHASES),
    renderPrecompiled(NAME, PURCHASES),
  ]);
  if (jsPort !== tsxPort) throw new Error("shared.tsx and shared.js do not render the same page");
  if (tsxPort !== precompiled)
    throw new Error("the transform output and the tree walk do not render the same page");
  console.log(`equivalence OK (${jsPort.length} bytes)`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
